// Regenerates sw.js's PRECACHE_URLS list from whatever is actually on disk,
// so new product images are always included automatically. Run this after
// adding/removing files in css/, js/, fonts/, images/, or icons/:
//
//   node scripts/gen-sw.js
//
// This script preserves whatever CACHE_VERSION is already in sw.js — it only
// rewrites the file list. Bumping the version (so phones fetch fresh content
// instead of serving old cached files forever) is a separate, manual edit:
// open sw.js and change the CACHE_VERSION string yourself.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SW_PATH = path.join(ROOT, "sw.js");

function walk(dir, exts) {
  if (!fs.existsSync(dir)) return [];
  let results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(walk(full, exts));
    } else if (exts.some((ext) => entry.name.toLowerCase().endsWith(ext))) {
      results.push(full);
    }
  }
  return results;
}

function toUrl(absPath) {
  return path.relative(ROOT, absPath).split(path.sep).join("/");
}

const IMG_EXTS = [".png", ".jpg", ".jpeg", ".webp"];
const FONT_EXTS = [".woff2"];

const jsFiles = fs.readdirSync(path.join(ROOT, "js"))
  .filter((f) => f.endsWith(".js"))
  .map((f) => `js/${f}`);

const files = [
  "./",
  "index.html",
  "product.html",
  "manifest.json",
  "css/style.css",
  ...jsFiles,
  ...walk(path.join(ROOT, "fonts"), FONT_EXTS).map(toUrl),
  ...walk(path.join(ROOT, "images"), IMG_EXTS).map(toUrl),
  ...walk(path.join(ROOT, "icons"), IMG_EXTS).map(toUrl),
];

// Preserve the existing CACHE_VERSION so regenerating the file list never
// silently resets a version bump you made by hand.
let version = "v1";
if (fs.existsSync(SW_PATH)) {
  const existing = fs.readFileSync(SW_PATH, "utf8");
  const match = existing.match(/const CACHE_VERSION = "([^"]+)"/);
  if (match) version = match[1];
}

const swContent = `// Auto-generated by scripts/gen-sw.js — re-run it after adding/removing
// files in css/, js/, fonts/, images/, or icons/:
//   node scripts/gen-sw.js
// That only rewrites PRECACHE_URLS below. The one line meant for hand-editing
// is CACHE_VERSION — bump it (v1 -> v2 -> ...) every time you update products
// or images, so installed phones fetch the new content on next launch instead
// of serving the old cached version forever. See CLAUDE.md for details.

const CACHE_VERSION = "${version}";
const CACHE_NAME = \`hallmark-cache-\${CACHE_VERSION}\`;

const PRECACHE_URLS = ${JSON.stringify(files, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
      .catch((err) => console.error("[sw] precache failed:", err))
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  // ignoreSearch: product.html?id=... must still match the precached
  // product.html entry — only the path was cached, not every ?id= variant.
  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((response) => {
          if (response.ok && response.type === "basic") {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        })
        .catch(() => {
          // Offline and not precached (e.g. an unexpected URL). For a page
          // navigation, fall back to the cached catalog instead of a dead
          // blank tab — there's nothing sensible to fall back to for an
          // image/font/etc, so those just fail as before.
          if (event.request.mode === "navigate") {
            return caches.match("index.html");
          }
          return cached;
        });
    })
  );
});
`;

fs.writeFileSync(SW_PATH, swContent);
console.log(`Wrote sw.js — ${files.length} files precached, version "${version}"`);
